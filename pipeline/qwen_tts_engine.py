class QwenTTSEngine(TTSEngine):
    """Qwen3-TTS engine: preset speakers + designed voices + voice clone.

    Uses three models:
      - CustomVoice model for preset speakers (generate_custom_voice)
      - VoiceDesign model for designed voices (generate_voice_design)
      - Base model for voice clone (generate_voice_clone)

    Inherits _loudnorm, get_duration from TTSEngine.
    Overrides synth_english and synth_chinese.
    """

    _custom_voice_model = None
    _voicedesign_model = None
    _base_model = None
    _device = None

    def __init__(self, model_path: str, device: str = "cuda:0",
                 base_model_path: str = "",
                 voicedesign_model_path: str = ""):
        self._model_path = model_path      # CustomVoice model
        self._base_model_path = base_model_path  # Base model for voice clone
        self._voicedesign_model_path = voicedesign_model_path  # VoiceDesign model
        QwenTTSEngine._device = device

    @classmethod
    def _get_custom_voice_model(cls, model_path: str, device: str):
        """Lazy-init CustomVoice model (class-level cache)."""
        if cls._custom_voice_model is None:
            # Ensure HF_ENDPOINT is set before any HF operations
            if "HF_ENDPOINT" not in os.environ and sys.platform == "win32":
                os.environ["HF_ENDPOINT"] = "https://hf-mirror.com"
            import torch
            from qwen_tts import Qwen3TTSModel
            resolved = str(Path(model_path).resolve())
            print(f"  [QwenTTS] Loading CustomVoice model from {resolved} on {device}...")
            cls._custom_voice_model = Qwen3TTSModel.from_pretrained(
                resolved,
                device_map=device,
                dtype=torch.bfloat16,
            )
            print(f"  [QwenTTS] CustomVoice model loaded.")
        return cls._custom_voice_model

    @classmethod
    def _get_voicedesign_model(cls, voicedesign_model_path: str, device: str):
        """Lazy-init VoiceDesign model for designed voices (class-level cache)."""
        if cls._voicedesign_model is None:
            # Ensure HF_ENDPOINT is set before any HF operations
            if "HF_ENDPOINT" not in os.environ and sys.platform == "win32":
                os.environ["HF_ENDPOINT"] = "https://hf-mirror.com"
            import torch
            from qwen_tts import Qwen3TTSModel
            resolved = str(Path(voicedesign_model_path).resolve())
            print(f"  [QwenTTS] Loading VoiceDesign model from {resolved} on {device}...")
            cls._voicedesign_model = Qwen3TTSModel.from_pretrained(
                resolved,
                device_map=device,
                dtype=torch.bfloat16,
            )
            print(f"  [QwenTTS] VoiceDesign model loaded.")
        return cls._voicedesign_model

    @classmethod
    def _get_base_model(cls, base_model_path: str, device: str):
        """Lazy-init Base model for voice clone (class-level cache)."""
        if cls._base_model is None:
            # Ensure HF_ENDPOINT is set before any HF operations
            if "HF_ENDPOINT" not in os.environ and sys.platform == "win32":
                os.environ["HF_ENDPOINT"] = "https://hf-mirror.com"
            import torch
            from qwen_tts import Qwen3TTSModel
            resolved = str(Path(base_model_path).resolve())
            print(f"  [QwenTTS] Loading Base model from {resolved} on {device}...")
            cls._base_model = Qwen3TTSModel.from_pretrained(
                resolved,
                device_map=device,
                dtype=torch.bfloat16,
            )
            print(f"  [QwenTTS] Base model loaded.")
        return cls._base_model

    def _synth(self, text: str, voice: str, language: str,
               out_path: str, rate: str) -> float:
        """Core synthesis: split sentences, generate, concat, convert, loudnorm.

        Preset speakers   -> CustomVoice model + generate_custom_voice
        Designed voices   -> VoiceDesign model + generate_voice_design
        Custom clone      -> Base model + generate_voice_clone
        """
        import numpy as np
        import soundfile as sf

        Path(out_path).parent.mkdir(parents=True, exist_ok=True)

        # Determine synthesis mode.
        # 查找顺序 custom → designed：冻结后的音色以克隆（ref_audio 锚定）为准，
        # 否则内置设计音色（如 Ella）冻结后仍会走设计模式，音色继续漂移。
        is_preset = voice in _PRESET_NAMES
        is_designed = False
        designed_meta = None
        custom_meta = None
        if not is_preset:
            custom_meta = get_custom_voice_meta(voice)
            if not custom_meta:
                designed_meta = get_designed_voice_meta(voice)
                if designed_meta:
                    is_designed = True
                else:
                    print(f"  [QwenTTS] Unknown voice '{voice}', falling back to {_DEFAULT_MALE}")
                    voice = _DEFAULT_MALE
                    is_preset = True

        # Load the appropriate model
        if is_preset:
            model = self._get_custom_voice_model(self._model_path, self._device)
        elif is_designed:
            if not self._voicedesign_model_path:
                raise RuntimeError(
                    "Designed voices require the VoiceDesign model. "
                    "Please set qwen_voicedesign_model_path in configuration."
                )
            model = self._get_voicedesign_model(self._voicedesign_model_path, self._device)
        else:
            if not self._base_model_path:
                raise RuntimeError(
                    "Voice clone requires the Base model. "
                    "Please set qwen_base_model_path in configuration."
                )
            model = self._get_base_model(self._base_model_path, self._device)

        all_audio = []
        sr = None

        for sentence in _split_sentences(text):
            sentence = sentence.strip()
            if not sentence:
                continue
            try:
                if is_preset:
                    wavs, sr = model.generate_custom_voice(
                        text=sentence,
                        language=language,
                        speaker=voice,
                        instruct=_DEFAULT_INSTRUCT,
                    )
                elif is_designed:
                    wavs, sr = model.generate_voice_design(
                        text=sentence,
                        language=language,
                        instruct=designed_meta["instruct"],
                    )
                else:
                    wavs, sr = model.generate_voice_clone(
                        text=sentence,
                        language=language,
                        ref_audio=custom_meta["ref_audio"],
                        ref_text=custom_meta["ref_text"],
                    )
                if wavs and len(wavs) > 0:
                    all_audio.append(wavs[0])
            except Exception as e:
                print(f"    [QwenTTS skip] {sentence[:40]}: {e}")

        if not all_audio:
            raise RuntimeError(f"Qwen-TTS produced no audio for: {text[:50]}")

        final_audio = all_audio[0] if len(all_audio) == 1 else np.concatenate(all_audio)

        # Write WAV, convert to MP3 with atempo speed adjustment
        wav_path = out_path.replace('.mp3', '_tmp.wav')
        sf.write(wav_path, final_audio, sr)

        speed = _rate_to_speed(rate)
        af = f"atempo={speed:.4f}" if 0.5 <= speed <= 2.0 and speed != 1.0 else "anull"
        subprocess.run(
            ["ffmpeg", "-y", "-i", wav_path,
             "-af", af,
             "-c:a", "libmp3lame", "-b:a", "128k",
             "-ar", "24000", "-ac", "1", out_path],
            check=True, capture_output=True
        )
        os.remove(wav_path)

        self._loudnorm(out_path)
        return self.get_duration(out_path)

    def synth_english(self, text: str, voice: str, out_path: str,
                      rate: str = "+0%") -> float:
        """Synthesize English text with Qwen3-TTS."""
        return self._synth(text, voice, "english", out_path, rate)

    def synth_chinese(self, text: str, voice: str, out_path: str,
                      rate: str = "-10%", max_retries: int = 5,
                      timeout: int = 30) -> float:
        """Synthesize Chinese text with Qwen3-TTS (native Chinese support)."""
        return self._synth(text, voice, "chinese", out_path, rate)
