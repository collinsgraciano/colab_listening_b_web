def _voice_config_path() -> Path:
    return Path(__file__).parent.parent / "configs" / "qwen_voice_config.json"


def _load_voice_config() -> dict:
    """Load qwen_voice_config.json, return defaults if not exists."""
    defaults = {
        "default_male": _DEFAULT_MALE,
        "default_female": _DEFAULT_FEMALE,
        "default_host_female": _DEFAULT_HOST_FEMALE,
        "custom_voices": [],
        "designed_voices": [],
        "candidate_voices": [],  # LLM 随机生成、待试听挑选的候选设计音色
    }
    path = _voice_config_path()
    if path.exists():
        try:
            saved = json.loads(path.read_text(encoding="utf-8"))
            # update 而非逐已知键回拷：保留未知键（如按模式分套的 modes）
            defaults.update(saved)
        except (json.JSONDecodeError, OSError):
            pass
    return defaults


def get_all_voices() -> list[dict]:
    """Return preset + designed + custom voices for UI dropdowns.

    同名去重：设计音色冻结为克隆音色后（custom_voices 同名存在），
    不再以设计音色身份重复出现（冻结版为准）。
    """
    config = _load_voice_config()
    custom_names = {cv["name"] for cv in config.get("custom_voices", [])}

    voices = list(QWEN_SPEAKERS)
    for dv in DESIGNED_VOICES_BUILTIN:
        if dv["name"] in custom_names:
            continue
        voices.append({
            "name": dv["name"],
            "desc": dv["desc"],
            "gender": dv["gender"],
            "lang": dv["lang"],
            "designed": True,
            "builtin": True,
        })
    for dv in config.get("designed_voices", []):
        if dv["name"] in custom_names:
            continue
        voices.append({
            "name": dv["name"],
            "desc": dv.get("description", ""),
            "gender": dv.get("gender", ""),
            "lang": dv.get("language", "en"),
            "designed": True,
            "builtin": False,
        })
    for cv in config.get("custom_voices", []):
        voices.append({
            "name": cv["name"],
            "desc": cv.get("description", ""),
            "gender": cv.get("gender", ""),
            "lang": cv.get("language", ""),
            "custom": True,
            # 冻结自设计音色（保存时自动生成的克隆版，音色稳定）
            "frozen": cv.get("frozen_from") == "designed",
        })
    return voices


def get_designed_voice_meta(name: str) -> dict | None:
    """Look up a designed voice (builtin → user-designed → candidate). None if not found.

    候选音色（candidate_voices，LLM 随机生成待挑选）与设计音色同构，
    也走 VoiceDesign 模型合成，故一并在此解析（试听端点无需注册即可用）。
    """
    for dv in DESIGNED_VOICES_BUILTIN:
        if dv["name"] == name:
            return dv
    config = _load_voice_config()
    for dv in config.get("designed_voices", []):
        if dv["name"] == name:
            return dv
    for cv in config.get("candidate_voices", []):
        if cv["name"] == name:
            return cv
    return None


def get_custom_voice_meta(name: str) -> dict | None:
    """Look up a custom voice by name. Returns None if not found."""
    config = _load_voice_config()
    for cv in config.get("custom_voices", []):
        if cv["name"] == name:
            return cv
    return None


def pick_zh_preset_fallback(name: str, gender: str = "", rank: int = 0,
                            structure: str | None = None) -> str:
    """中文合成音色回退校正 + 同性别错开。

    绑定的预设为外语（en/ja/ko）时换成中文性别预设；rank 为同性别分组序号
    （0=第一默认, 1=第二默认），避免同性别两角色中文台词撞音色。
    克隆/设计音色不受影响（非 _PRESET_LANG 成员，原样返回）。
    """
    if _PRESET_LANG.get(name, "zh") == "zh":
        return name
    defaults = _resolve_mode_defaults(_load_voice_config(), structure,
                                      QWEN_VOICE_DEFAULTS)
    if (gender or "").lower() == "male":
        return _gender_default(defaults, "default_male_zh", rank)
    return _gender_default(defaults, "default_female_zh", rank)


def gender_default_ranks(script: dict) -> dict[str, int]:
    """char_a/b/c 未绑定 qwen 音色者的同性别分组序号（0=第一默认,1=第二,2=第三）."""
    return _same_gender_ranks([
        (key, (script.get(f"{key}_gender") or "").lower(),
         bool((script.get(f"{key}_qwen_speaker") or "").strip()))
        for key in ("char_a", "char_b", "char_c")
    ])


def build_qwen_voice_map(script: dict, structure: str | None = None) -> dict:
    """Build voice_map for Qwen-TTS.

    Priority: script['char_X_qwen_speaker'] (from library) > auto by gender.
    Default speakers come from qwen_voice_config.json 按模式分套默认音色：
    未绑定的同性别角色依次取第一/第二/第三默认（char_a→char_b→char_c），
    性别不同时各自取第一默认。structure 决定用哪个模式的默认套
    （缺省读 script['structure']，再兜底 original）。
    """
    if not structure:
        structure = script.get("structure") or "original"
    defaults = _resolve_mode_defaults(_load_voice_config(), structure,
                                      QWEN_VOICE_DEFAULTS)
    ranks = gender_default_ranks(script)

    voice_map = {}
    for key in ["char_a", "char_b", "char_c", "host"]:
        # Priority 1: qwen_speaker from script (set by library binding)
        speaker = script.get(f"{key}_qwen_speaker", "")
        if speaker:
            voice_map[key] = speaker
            continue
        # Priority 2: auto by gender (+ 同性别错开)
        gender = script.get(f"{key}_gender", "").lower()
        if not gender:
            continue
        if key == "host":
            voice_map[key] = (defaults["default_host_female"] if gender == "female"
                              else _gender_default(defaults, "default_host_male", 0))
        else:
            base = "default_female" if gender == "female" else "default_male"
            voice_map[key] = _gender_default(defaults, base, ranks.get(key, 0))
    return voice_map


